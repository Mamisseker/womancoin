/**
 * Единицы измерения баланса.
 *
 * За тап выдаётся 0.000001 токена — настолько мелкое значение, что
 * хранить его во «плавающем» виде нельзя: накопление дробей быстро
 * упирается в точность и в Math.floor при разборе сохранения, из-за
 * чего монеты молча превращались бы в ноль.
 *
 * Поэтому внутренний баланс — ЦЕЛОЕ число микро-единиц:
 *   1 токен = 1 000 000 микро-единиц.
 * Один тап = 1 микро-единица. Все арифметические операции остаются
 * целочисленными, а форматирование в токены происходит только на выводе.
 */

export const MICRO = 1_000_000;

/** Сколько микро-единиц выдаёт один тап при нулевом уровне урона. */
export const MICRO_PER_TAP = 1;

/**
 * Форматирует баланс из микро-единиц в строку токенов.
 *
 * Масштаб подбирается по величине значения, чтобы строка не разрасталась
 * и не превращалась в «0.000000» после первого же тапа:
 *   0            → «0»
 *   до 1000      → 6 знаков после запятой (виден каждый тап)
 *   до 1 000 000 → 3 знака
 *   дальше        → целые с разделителями
 */
export const formatTokens = (micro: number): string => {
  const safe = Number.isFinite(micro) ? Math.max(0, micro) : 0;
  if (safe === 0) return '0';

  const tokens = safe / MICRO;

  if (tokens < 0.001) {
    return tokens.toFixed(6);
  }
  if (tokens < 1) {
    return tokens.toFixed(3);
  }
  if (tokens < 1_000) {
    return tokens.toLocaleString('ru-RU', { maximumFractionDigits: 3 });
  }
  return Math.floor(tokens).toLocaleString('ru-RU');
};

/**
 * Компактная подпись «+0.000001 /тап» под прогрессом прокачки.
 * Показывает прирост за тап в токенах.
 */
export const formatTapGain = (microPerTap: number): string =>
  `+${formatTokens(microPerTap)} /тап`;